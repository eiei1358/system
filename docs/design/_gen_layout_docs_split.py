# uc_name 単位にグルーピング（出現順を維持）
from collections import OrderedDict
groups = OrderedDict()
for args, kw in SCREENS:
    uc = args[0]
    groups.setdefault(uc, []).append((args, kw))

for uc, items in groups.items():
    doc = new_doc()
    for i,(args, kw) in enumerate(items):
        kw2 = dict(kw); kw2['page_break_before'] = (i>0)
        render_screen(doc, *args, **kw2)
    fname = f"{PREFIX[uc]}_{uc}.docx"
    doc.save(os.path.join(OUTDIR, fname))
    print('saved:', fname, f'({len(items)} screens)')

print('\nTotal files:', len(groups))
