CIRC = "①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳"
C = CIRC

def set_cell_bg(cell, color="EFEFEF"):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:color'), 'auto'); shd.set(qn('w:fill'), color)
    tcPr.append(shd)

def set_mono(cell):
    for p in cell.paragraphs:
        for r in p.runs:
            r.font.name = 'MS Gothic'
            r._element.get_or_add_rPr().get_or_add_rFonts().set(qn('w:eastAsia'), 'MS Gothic')
            r.font.size = Pt(9)

def new_doc():
    doc = Document()
    style = doc.styles['Normal']
    style.font.name = 'Yu Gothic'; style.font.size = Pt(10.5)
    rpr = style.element.get_or_add_rPr(); rfonts = rpr.get_or_add_rFonts()
    rfonts.set(qn('w:eastAsia'), 'Yu Gothic')
    return doc

def render_screen(doc, uc_name, screen_id, screen_name, layout_text, parts, operation,
                  tantou="", created="2025/6/15", first_revision="2025/6/15", page_break_before=False):
    if page_break_before:
        doc.add_page_break()
    # ヘッダー表
    h = doc.add_table(rows=2, cols=7); h.style = 'Table Grid'
    labels = ['システム名','ユースケース名','グループ名','承認印','作成日','担当','版数']
    values = ['フリマシステム', uc_name, 'ヤマグチーム', '', created, tantou, 'ver. 1.0']
    for i,(lab,val) in enumerate(zip(labels,values)):
        c0 = h.cell(0,i); c0.text = lab; set_cell_bg(c0)
        for r in c0.paragraphs[0].runs: r.bold = True; r.font.size = Pt(9)
        c1 = h.cell(1,i); c1.text = val
        for r in c1.paragraphs[0].runs: r.font.size = Pt(9)
    # 画面ID / 画面名
    t = doc.add_table(rows=2, cols=2); t.style = 'Table Grid'; t.columns[0].width = Pt(70)
    for i,(lab,val) in enumerate([('画面ID', screen_id), ('画面名', screen_name)]):
        cl = t.cell(i,0); cl.text = lab; set_cell_bg(cl)
        for r in cl.paragraphs[0].runs: r.bold = True
        t.cell(i,1).text = val
    # 画面レイアウト
    pl = doc.add_paragraph(); rr = pl.add_run('画面レイアウト'); rr.bold = True; rr.font.size = Pt(11)
    lt = doc.add_table(rows=1, cols=1); lt.style = 'Table Grid'
    cell = lt.cell(0,0); cell.text = ''
    for line in layout_text.split('\n'):
        p = cell.add_paragraph(line)
        p.paragraph_format.space_after = Pt(0); p.paragraph_format.space_before = Pt(0)
    cell.paragraphs[0]._element.getparent().remove(cell.paragraphs[0]._element)
    set_mono(cell)
    # 部品説明
    pp = doc.add_paragraph(); rr = pp.add_run('部品説明'); rr.bold = True; rr.font.size = Pt(11)
    pt = doc.add_table(rows=1, cols=3); pt.style = 'Table Grid'
    for i,htext in enumerate(['識別','入出力項目','説明']):
        c = pt.cell(0,i); c.text = htext; set_cell_bg(c)
        for r in c.paragraphs[0].runs: r.bold = True; r.font.size = Pt(9)
    pt.columns[0].width = Pt(40); pt.columns[1].width = Pt(120); pt.columns[2].width = Pt(280)
    for ident, item, desc in parts:
        row = pt.add_row().cells
        row[0].text = ident; row[1].text = item; row[2].text = desc
        for c in row:
            for r in c.paragraphs[0].runs: r.font.size = Pt(9)
    # 操作
    op = doc.add_paragraph(); rr = op.add_run('操作'); rr.bold = True; rr.font.size = Pt(11)
    for line in operation.split('\n'):
        doc.add_paragraph(line)
    # 改定日 / 改定者
    rev = doc.add_table(rows=2, cols=8); rev.style = 'Table Grid'
    rev.cell(0,0).text = '改定日'; set_cell_bg(rev.cell(0,0))
    rev.cell(1,0).text = '改定者'; set_cell_bg(rev.cell(1,0))
    rev.cell(0,1).text = first_revision
    for j in range(2,8): rev.cell(0,j).text = '/  /'
    for c in [rev.cell(0,0), rev.cell(1,0)]:
        for r in c.paragraphs[0].runs: r.bold = True; r.font.size = Pt(9)

